import {test,expect,type Page} from '@playwright/test'
async function seed(page:Page,recovery=false){
  await page.evaluate(async recovery=>{
    const db=await new Promise<IDBDatabase>(resolve=>{const r=indexedDB.open('gymbeast');r.onsuccess=()=>resolve(r.result)})
    const profile=await new Promise<any>(resolve=>{const r=db.transaction('items').objectStore('items').get(['local','profile','self']);r.onsuccess=()=>resolve(r.result)})
    const tx=db.transaction('items','readwrite'),store=tx.objectStore('items')
    const exercises=['bench-barbell','squat','pulldown'].map((catalogId,i)=>({id:'e'+i,catalogId,name:['Press banca','Sentadilla','Jalón'][i],original:'Prueba',sets:1,min:10,max:10,load:65,unit:'kg',mode:'external',rest:0,type:'work'}))
    const put=(kind:string,id:string,data:any)=>store.put({owner:'local',kind,id,version:1,data})
    profile.data.petPlans=[{from:'2026-01-05',target:5,companion:'Dragón'}];store.put(profile)
    if(!recovery)for(let i=0;i<10;i++){
      const started=Date.parse('2026-01-05T12:00:00Z')+(Math.floor(i/5)*7+i%5)*86400000,id='old'+i
      put('session',id,{title:id,date:new Date(started).toISOString().slice(0,10),started,ended:started+60000,cycleId:'old',dayId:id,companion:'Dragón',exercises})
      for(const e of exercises)put('set',id+e.id,{sessionId:id,exerciseId:e.id,kg:i===9?65:60,reps:10,done:true,created:started,type:'work'})
    }
    else for(let i=0;i<4;i++)put('session','recovery'+i,{title:'Volver a crecer '+i,date:'2026-02-02',started:Date.parse('2026-02-02T12:00:00Z')+i*1000,
      cycleId:'recovery',dayId:'day'+i,companion:'Dragón',companionXpAtStart:i*25,exercises})
    await new Promise<void>(resolve=>{tx.oncomplete=()=>resolve()});db.close()
  },recovery)
}
test('misiones, insignias, muerte y recuperación conservan el estado offline',async({page,context},info)=>{
  test.setTimeout(60000)
  await page.clock.setFixedTime(new Date('2026-01-18T15:00:00Z'))
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('gymbeast-active-account', 'local'))
  await page.reload()
  await page.getByLabel('Tu nombre').fill('Misiones')
  await page.getByRole('button',{name:/Dragón/}).click()
  await page.getByRole('button',{name:'Confirmar compañero'}).click()
  await expect(page.getByRole('heading',{name:'Hola, Misiones'})).toBeVisible()
  await seed(page)
  await page.goto('/progreso')
  await expect(page.getByLabel('Misión cumplir el plan')).toHaveAttribute('value','5')
  await expect(page.getByLabel('Misión mejorar cargas')).toHaveAttribute('value','3')
  await expect(page.getByText('Insignia: Plan cumplido',{exact:true})).toBeVisible()
  await expect(page.getByText('Insignia: Más fuerte',{exact:true})).toBeVisible()
  await page.getByText('Logros avanzados',{exact:true}).click()
  await expect(page.locator('.achievement[data-complete="true"]')).toHaveCount(1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('misiones.png'),fullPage:true})
  await page.waitForFunction(()=>!!navigator.serviceWorker.controller)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByLabel('Misión mejorar cargas')).toHaveAttribute('value','3')
  await page.clock.setFixedTime(new Date('2026-01-26T15:00:00Z'));await page.goto('/')
  await expect(page.getByLabel('Vida de la mascota')).toHaveAttribute('value','50')
  await page.clock.setFixedTime(new Date('2026-02-02T15:00:00Z'));await page.reload()
  await expect(page.getByLabel('Vida de la mascota')).toHaveAttribute('value','0')
  await expect(page.locator('.habitat [data-form="0"]')).toBeVisible()
  await seed(page,true)
  for(let i=0;i<4;i++){
    await page.goto('/sesion/recovery'+i)
    await expect(page.locator('.exercise-session')).toHaveCount(3)
    for(const exercise of await page.locator('.exercise-session').all())await exercise.getByRole('button',{name:'Registrar serie 1',exact:true}).click()
    await page.getByRole('button',{name:'Finalizar entrenamiento'}).click()
    await expect(page.getByRole('status',{name:'+25 EXP · +20 de oro'})).toBeVisible()
    await page.goto('/')
    await expect(page.getByLabel('Vida de la mascota')).toHaveAttribute('value',i===3?'100':'0')
  }
  await page.reload()
  await expect(page.locator('.habitat [data-form="1"]')).toBeVisible()
  await expect(page.getByLabel('Vida de la mascota')).toHaveAttribute('value','100')
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/progreso')
  await expect(page.getByLabel('Misión cumplir el plan')).toHaveAttribute('value','1')
  await expect(page.getByText(/Tus insignias semanales/)).toBeVisible()
})
