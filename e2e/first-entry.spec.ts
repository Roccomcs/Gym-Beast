import { expect, test } from '@playwright/test'

test('primer ingreso y cierre de sesión local', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const localEntry = page.getByRole('button', { name: 'Probar en este dispositivo' })
  await expect(localEntry).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('01-acceso.png'), fullPage: true })
  await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click()
  await page.screenshot({ path: info.outputPath('02-registro.png'), fullPage: true })
  await page.evaluate(() => localStorage.setItem('gymbeast-active-account', 'local'))
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Armá tu equipo' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('03-primer-companero.png'), fullPage: true })
  await page.getByLabel('Tu nombre').fill('Rocco Demo')
  await page.getByRole('button', { name: /Dragón/ }).click()
  await page.getByLabel('Nombre de tu compañero').fill('Gordo')
  await page.getByRole('button', { name: 'Confirmar compañero' }).click()
  await expect(page.getByRole('heading', { name: 'Hola, Rocco Demo' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('04-inicio.png'), fullPage: true })
  await page.getByRole('link', { name: 'Perfil', exact: true }).click()
  await page.getByRole('button', { name: 'Cerrar sesión' }).click()
  await expect(localEntry).toHaveCount(0)
  await page.evaluate(() => localStorage.setItem('gymbeast-active-account', 'local'))
  await page.reload()
  await page.getByRole('link', { name: 'Inicio', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Gordo' })).toBeVisible()
})
