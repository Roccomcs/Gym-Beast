import {test,expect} from '@playwright/test'
import {seedMobile,noOverflow} from './mobile/helpers'
import {mobileItems} from '../tests/mobile-fixture'
import {chooseBuilderExercise,configureBuilderDay,saveBuilderDay,saveBuilderRoutine} from './builder-helpers'

test('crear abre el día uno, selecciona varias imágenes y asigna la identidad por días',async({page},info)=>{
 await page.setViewportSize(info.project.use.viewport??{width:320,height:780})
 await seedMobile(page,mobileItems().filter(e=>e.kind==='profile'))
 await page.goto('/rutinas')
 await page.getByRole('link',{name:'Crear rutina',exact:true}).click()
 await expect(page).toHaveURL(/editor\/manual$/)
 await expect(page.getByRole('heading',{name:'Nueva rutina',exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Día 1',exact:true})).toBeVisible()
 await expect(page.getByRole('link',{name:'Crear manualmente'})).toHaveCount(0)
 await expect(page.getByRole('link',{name:'Importar texto'})).toHaveCount(0)
 await expect(page.getByLabel('Nombre de la rutina')).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Agregar día',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Continuar',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'Pecho',exact:true}).click()
 await expect(page.getByRole('button',{name:'Sentadilla libre',exact:true})).toHaveCount(0)
 await chooseBuilderExercise(page,'Press banca')
 await page.getByRole('searchbox',{name:'Buscar ejercicio',exact:true}).fill('')
 await chooseBuilderExercise(page,'Aperturas')
 await expect(page.getByRole('status')).toHaveText('2 seleccionados')
 await noOverflow(page)
 const footer=await page.locator('.builder-selection-footer').boundingBox()
 expect(footer!.y+footer!.height).toBeLessThan((await page.viewportSize())!.height-50)
 await page.screenshot({path:info.outputPath('seleccion.png'),fullPage:false})
 await page.getByRole('button',{name:'Continuar',exact:true}).click()
 await page.getByLabel('Peso de Press banca (kg)',{exact:true}).fill('62,5')
 await page.getByLabel('Repeticiones de Press banca',{exact:true}).fill('8')
 await saveBuilderDay(page)
 for(let n=2;n<=5;n++){
  await page.getByRole('button',{name:'Agregar día',exact:true}).click()
  await configureBuilderDay(page,['Remo bajo'])
  await saveBuilderDay(page)
  if(n>=3){
   await expect(page.locator('.builder-preview h2')).toHaveText(n===3?'Rutina básica':n===4?'Rutina intermedia':'Rutina avanzada')
   await expect(page.locator('.builder-preview .rank-cover')).toHaveCSS('background-image',new RegExp(n===3?'basic':n===4?'intermediate':'advanced'))
  }
 }
 await page.screenshot({path:info.outputPath('cinco-dias.png'),fullPage:true})
 await saveBuilderRoutine(page)
 const own=page.locator('.my-routine').filter({has:page.getByRole('heading',{name:'Rutina avanzada',exact:true})})
 await expect(own).toBeVisible()
 await own.getByRole('link',{name:'Editar',exact:true}).click()
 await page.getByText('Nombre y portada',{exact:true}).click()
 await page.getByLabel('Nombre de la rutina',{exact:true}).fill('Mi semana')
 await page.getByLabel('Foto de la rutina',{exact:true}).setInputFiles('public/icon-192.png')
 await expect(page.getByRole('img',{name:'Foto de la rutina',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Guardar cambios',exact:true}).click()
 await expect(page.locator('.my-routine').getByRole('heading',{name:'Mi semana',exact:true})).toBeVisible()
 await page.reload()
 await page.getByRole('button',{name:'Usar rutina',exact:true}).click()
 await page.getByRole('button',{name:'Empezar',exact:true}).click()
 await expect(page.locator('.exercise-session').first().getByLabel('kg',{exact:true}).first()).toHaveValue('62.5')
 await expect(page.locator('.exercise-session').first().getByLabel('Reps',{exact:true}).first()).toHaveValue('8')
 await noOverflow(page)
})

test('el borrador conserva selección, orden y valores al recargar, con cardio sin peso',async({page,context},info)=>{
 await page.setViewportSize(info.project.use.viewport??{width:390,height:780})
 await seedMobile(page,mobileItems())
 await page.goto('/editor')
 await expect(page).toHaveURL(/editor\/manual$/)
 await chooseBuilderExercise(page,'Bicicleta fija');await chooseBuilderExercise(page,'Face pull con cuerda')
 await page.reload()
 await expect(page.getByRole('status')).toHaveText('2 seleccionados')
 await page.getByRole('button',{name:'Continuar',exact:true}).click()
 await page.getByLabel('Segundos de Bicicleta fija',{exact:true}).fill('1200')
 await page.getByRole('combobox',{name:'Uso de Bicicleta fija',exact:true}).selectOption('warmup')
 await expect(page.getByLabel('Peso de Bicicleta fija (kg)',{exact:true})).toHaveCount(0)
 await page.getByLabel('Peso de Face pull con cuerda (kg)',{exact:true}).fill('15')
 await expect(page.locator('[data-draft-ready=true]')).toBeVisible()
 await page.reload()
 await expect(page.getByLabel('Segundos de Bicicleta fija',{exact:true})).toHaveValue('1200')
 await expect(page.getByLabel('Peso de Face pull con cuerda (kg)',{exact:true})).toHaveValue('15')
 await page.setViewportSize({width:info.project.use.viewport?.width??390,height:430})
 await page.getByLabel('Peso de Face pull con cuerda (kg)',{exact:true}).focus()
 await noOverflow(page)
 await page.screenshot({path:info.outputPath('configurar-teclado.png')})
 await page.setViewportSize(info.project.use.viewport??{width:390,height:780})
 await saveBuilderDay(page)
 await expect(page.locator('.builder-day li strong')).toHaveText(['Bicicleta fija','Face pull con cuerda'])
 await saveBuilderRoutine(page)
 await page.getByRole('link',{name:'Crear rutina',exact:true}).click()
 await expect(page.getByRole('status')).toHaveText('0 seleccionados')
 await expect(page.getByRole('heading',{name:'Día 1',exact:true})).toBeVisible()
 await page.evaluate(async()=>{await navigator.serviceWorker.ready});await page.reload()
 await page.waitForFunction(()=>!!navigator.serviceWorker.controller)
 await context.setOffline(true);await page.reload()
 await expect(page.getByRole('heading',{name:'Nueva rutina',exact:true})).toBeVisible()
})

