test('retoma el alta y muestra las diez portadas en pantalla angosta', async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 720 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Probar en este dispositivo' }).click()
  await page.getByLabel('Tu nombre').fill('Ari')
  await page.getByLabel('Peso (opcional)').fill('72')
  await page.getByRole('button', { name: /Lobo/ }).click()
  await expect.poll(() => page.evaluate(async () => {
    const database = await new Promise<IDBDatabase>((resolve, reject) => {
      const request = indexedDB.open('gymbeast')
      request.onsuccess = () => resolve(request.result)
      request.onerror = () => reject(request.error)
    })
    return new Promise<string>((resolve, reject) => {
      const request = database.transaction('onboarding').objectStore('onboarding').get('local')
      request.onsuccess = () => { database.close(); resolve(request.result?.profile?.companion) }
      request.onerror = () => { database.close(); reject(request.error) }
    })
  })).toBe('Lobo')
  await page.reload()
  await expect(page.getByLabel('Tu nombre')).toHaveValue('Ari')
  await expect(page.getByLabel('Peso (opcional)')).toHaveValue('72')
  await expect(page.getByRole('button', { name: /Lobo/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Confirmar compañero' }).click()
  await page.getByRole('link', { name: 'Rutinas', exact: true }).click()
  await expect(page.locator('.program-cover')).toHaveCount(10)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.screenshot({ path: info.outputPath('rutinas-320.png') })
})

test('restaura un respaldo local y protege los datos existentes', async ({ page }) => {
  await onboard(page)
  await page.getByRole('link', { name: 'Perfil' }).click()
  const input = page.getByLabel('Archivo de respaldo')
  const restore = page.getByRole('button', { name: 'Restaurar respaldo local' })
  await input.setInputFiles({ name: 'invalido.json', mimeType: 'application/json', buffer: Buffer.from('{') })
  await restore.click()
  await expect(page.getByText('El archivo no contiene JSON válido.')).toBeVisible()
  const item = { owner: 'otro', id: 'rutina-1', version: 1, kind: 'routine',
    data: { name: 'Rutina restaurada', version: 1, source: '', days: [] } }
  await input.setInputFiles({ name: 'gymbeast.json', mimeType: 'application/json',
    buffer: Buffer.from(JSON.stringify({ version: 1, items: [item] })) })
  await restore.click()
  await expect(page.getByText('Registros restaurados: 1')).toBeVisible()
  await restore.click()
  await expect(page.getByText('La restauración requiere un espacio local', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: 'Rutinas', exact: true }).click()
  await page.getByRole('button', { name: 'Mis rutinas' }).click()
  await expect(page.getByRole('heading', { name: 'Rutina restaurada' })).toBeVisible()
})

