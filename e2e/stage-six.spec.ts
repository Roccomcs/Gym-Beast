import { expect, test, type Page } from '@playwright/test'
async function onboard(page: Page) {
  await page.setViewportSize({width:320,height:780})
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('gymbeast-active-account', 'local'))
  await page.reload()
  await page.getByLabel('Tu nombre').fill('Prueba etapa 6')
  await page.getByRole('button',{name:/Dragón/}).click()
  await page.getByRole('button',{name:'Confirmar compañero'}).click()
  await expect(page.getByRole('heading',{name:'Hola, Prueba etapa 6'})).toBeVisible()
}
test('guarda un ejercicio propio, reutiliza su identidad y conserva los músculos offline',async({page,context},info)=>{
  await onboard(page)
  await page.goto('/editor/manual')
  await page.getByText('Crear ejercicio propio',{exact:true}).click()
  await page.getByLabel('Nombre del ejercicio',{exact:true}).fill('Remo de mi gimnasio')
  await page.getByRole('combobox',{name:'Músculo principal',exact:true}).selectOption('Espalda')
  await page.getByRole('combobox',{name:'Equipo',exact:true}).selectOption('Máquina')
  await page.getByText('Músculos secundarios',{exact:true}).click()
  await page.getByRole('checkbox',{name:'Bíceps',exact:true}).check()
  await page.getByRole('button',{name:'Agregar a este día',exact:true}).click()
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByLabel('Series de Remo de mi gimnasio',{exact:true}).fill('2')
  await page.getByLabel('Repeticiones de Remo de mi gimnasio',{exact:true}).fill('8')
  await page.getByLabel('Peso de Remo de mi gimnasio (kg)',{exact:true}).fill('27,5')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('propio-320.png'),fullPage:true})
  await saveBuilderDay(page);await saveBuilderRoutine(page)
  await page.getByRole('link',{name:'Crear rutina',exact:true}).click()
  await configureBuilderDay(page,['Remo de mi gimnasio'])
  await saveBuilderDay(page);await saveBuilderRoutine(page)
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.reload();await page.waitForFunction(()=>!!navigator.serviceWorker.controller)
  await context.setOffline(true);await page.reload()
  await page.getByRole('link',{name:'Editar',exact:true}).first().click()
  await expect(page.locator('.builder-day li strong')).toHaveText(['Remo de mi gimnasio'])
  const customIds = await page.evaluate(async()=>{
    const database=await new Promise<IDBDatabase>(resolve=>{const r=indexedDB.open('gymbeast');r.onsuccess=()=>resolve(r.result)})
    const rows=await new Promise<any[]>(resolve=>{const r=database.transaction('items').objectStore('items').getAll();r.onsuccess=()=>resolve(r.result)})
    database.close()
    return rows.filter(row=>row.kind==='routine').flatMap(row=>row.data.days.flatMap((day:any)=>day.exercises.map((exercise:any)=>exercise.custom.id)))
  })
  expect(customIds).toHaveLength(2); expect(new Set(customIds).size).toBe(1)
})

