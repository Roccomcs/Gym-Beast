test('repetir Fuerza base alterna la semana sin modificar las tres sesiones anteriores',async({page})=>{
  await onboard(page)
  await page.getByRole('link',{name:'Rutinas',exact:true}).click()
  await selectLegacyProgram(page)
  await page.getByRole('button',{name:'Usar rutina',exact:true}).click()
  for(let day=0;day<3;day++){
    await page.getByRole('button',{name:'Empezar',exact:true}).click()
    await expect(page.locator('.exercise-session')).toHaveCount(3)
    for(const exercise of await page.locator('.exercise-session').all()) await exercise.getByRole('button',{name:'Registrar serie 1',exact:true}).click()
    await page.getByRole('button',{name:'Finalizar entrenamiento',exact:true}).click()
    await page.getByRole('link',{name:'Entrenar',exact:true}).click()
  }
  await page.getByRole('button',{name:'Repetir ciclo',exact:true}).click()
  await page.getByRole('button',{name:'Empezar',exact:true}).click()
  await expect(page.locator('.exercise-session h2').nth(1)).toHaveText('Press militar con barra')
  const earlier=await page.evaluate(async()=>{
    const database=await new Promise<IDBDatabase>(resolve=>{const r=indexedDB.open('gymbeast');r.onsuccess=()=>resolve(r.result)})
    const rows=await new Promise<any[]>(resolve=>{const r=database.transaction('items').objectStore('items').getAll();r.onsuccess=()=>resolve(r.result)})
    database.close()
    return rows.filter(row=>row.kind==='session'&&row.data.ended).sort((a,b)=>a.data.started-b.data.started).map(row=>row.data.exercises[1].catalogId)
  })
  expect(earlier).toEqual(['bench-barbell','overhead-press','bench-barbell'])
})
